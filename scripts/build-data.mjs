// Builds js/data.js from data/research.json.
// Fills the few gaps the research left open with stated assumptions, and adds short headlines
// for the context facts. Run: node scripts/build-data.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const d = JSON.parse(readFileSync(new URL('../data/research.json', import.meta.url)));
const byId = Object.fromEntries(d.options.map((o) => [o.id, o]));

// Hydro: no published price, only a derived ~$73/MWh point estimate. Use it as the range.
const hydro = byId.hydro;
if (hydro.lcoe_usd_mwh.low == null) {
  const v = hydro.lcoe_usd_mwh.derived_estimate;
  hydro.lcoe_usd_mwh.low = v; hydro.lcoe_usd_mwh.high = v;
}
// Hydro PPAs are grid-delivered, so time to power is the grid connection time.
if (hydro.years_to_power.low == null) {
  hydro.years_to_power = { ...byId.grid.years_to_power, note: hydro.years_to_power.note };
}

// Short display names; the research's fuller name is kept as longName.
const short = {
  grid: 'Grid connection', gas_ccgt: 'On-site gas (combined cycle)', gas_recip_or_aero: 'Gas engines & aero turbines',
  fuel_cells: 'Fuel cells', solar_storage: 'Solar + batteries', wind_storage: 'Wind + batteries',
  solar_wind_gas_hybrid: 'Renewables + gas firming', nuclear_existing: 'Existing nuclear',
  smr: 'Small modular reactors', geothermal: 'Next-gen geothermal', hydro: 'Existing hydro',
};
for (const o of d.options) { o.longName = o.name; o.name = short[o.id] || o.name; }

// Short headline + one-line summary for the fact cards; the full sourced fact stays in `fact`.
const cards = [
  ['4.4% → up to 12%', 'Share of US electricity used by data centers in 2023, and LBNL\'s projection for 2028.'],
  ['~945 TWh by 2030', 'Global data center use more than doubles (IEA); they drive almost half of US demand growth.'],
  ['4+ years', 'Median wait from interconnection request to operation for new US generation.'],
  ['1.5–2 years late', 'How much longer utilities quote time to power than developers expect.'],
  ['~100 GW backlog', 'GE Vernova\'s gas turbine backlog; new heavy-duty orders wait ~3 years.'],
  ['233 GW queue', 'ERCOT\'s large-load queue by late 2025, over 70% of it data centers.'],
  ['$37–$255/MWh', 'Unsubsidized cost range across wind, solar, gas and new nuclear (Lazard 2026).'],
  ['9.03¢/kWh', 'Average US industrial power price, Jan–Jul 2026, up 6% on a year earlier.'],
];
d.context.forEach((c, i) => { [c.headline, c.short] = cards[i] || ['', c.fact]; });

const out = `// Generated by scripts/build-data.mjs from data/research.json. Do not edit by hand.\nexport default ${JSON.stringify(d, null, 1)};\n`;
writeFileSync(new URL('../js/data.js', import.meta.url), out);
console.log(`js/data.js: ${d.options.length} options, ${d.regions.length} regions, ${d.sources.length} sources`);
